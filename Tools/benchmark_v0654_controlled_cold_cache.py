"""Controlled true-cold benchmark for Performance Passport intelligence.

This benchmark answers one specific question:

    How long does Training Coach take when the athlete's persistent intelligence
    really is cold?

Safety model
------------
1. Read and back up EVERY athlete_intelligence row for the selected athlete.
2. Remove only those derived/materialised rows.
3. Start the measured Training Coach build.
4. Immediately run the same build again to show warm-navigation time.
5. In a finally block, remove rows generated by the benchmark and restore the
   exact backed-up rows.

No activity, athlete, goal, PB override, health, training-block or other source
data is deleted or edited.

A small on-disk backup file is also written before deletion. If Python were
forcibly terminated before the finally block ran, the cache rows are still
recoverable and, in any case, are derived/rebuildable intelligence rather than
athlete source data.

Run:
    python tools/benchmark_v0654_controlled_cold_cache.py --athlete 1
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sqlite3
import time
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core.database import get_connection, initialise_database
from core.training_coach import build_training_coach_detail


BACKUP_DIR = ROOT / "benchmarks" / "cache_backups"


def _table_columns(conn: sqlite3.Connection) -> list[str]:
    rows = conn.execute("PRAGMA table_info(athlete_intelligence)").fetchall()
    return [str(row[1]) for row in rows]


def _serialisable(value):
    if isinstance(value, bytes):
        return {"__bytes_hex__": value.hex()}
    return value


def _deserialise(value):
    if isinstance(value, dict) and "__bytes_hex__" in value:
        return bytes.fromhex(value["__bytes_hex__"])
    return value


def _backup_rows(athlete_id: int):
    conn = get_connection()
    try:
        columns = _table_columns(conn)
        if not columns:
            raise RuntimeError("athlete_intelligence table does not exist")

        rows = conn.execute(
            "SELECT * FROM athlete_intelligence WHERE athlete_id = ?",
            (int(athlete_id),),
        ).fetchall()

        payload_rows = [
            [_serialisable(value) for value in tuple(row)]
            for row in rows
        ]
        return columns, payload_rows
    finally:
        conn.close()


def _write_disk_backup(athlete_id: int, columns, rows) -> Path:
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    path = BACKUP_DIR / f"athlete-intelligence-{athlete_id}-{stamp}.json"
    path.write_text(
        json.dumps(
            {
                "athlete_id": int(athlete_id),
                "columns": columns,
                "rows": rows,
            },
            indent=2,
            default=str,
        ),
        encoding="utf-8",
    )
    return path


def _delete_intelligence(athlete_id: int) -> int:
    conn = get_connection()
    try:
        cursor = conn.execute(
            "DELETE FROM athlete_intelligence WHERE athlete_id = ?",
            (int(athlete_id),),
        )
        conn.commit()
        return int(cursor.rowcount or 0)
    finally:
        conn.close()


def _restore_rows(athlete_id: int, columns, rows) -> None:
    conn = get_connection()
    try:
        conn.execute(
            "DELETE FROM athlete_intelligence WHERE athlete_id = ?",
            (int(athlete_id),),
        )

        if rows:
            placeholders = ",".join("?" for _ in columns)
            column_sql = ",".join(f'"{name}"' for name in columns)
            sql = (
                f"INSERT INTO athlete_intelligence ({column_sql}) "
                f"VALUES ({placeholders})"
            )
            restored = [
                tuple(_deserialise(value) for value in row)
                for row in rows
            ]
            conn.executemany(sql, restored)

        conn.commit()
    finally:
        conn.close()


def _count_rows(athlete_id: int) -> int:
    conn = get_connection()
    try:
        row = conn.execute(
            "SELECT COUNT(*) FROM athlete_intelligence WHERE athlete_id = ?",
            (int(athlete_id),),
        ).fetchone()
        return int(row[0] or 0)
    finally:
        conn.close()


def _athlete_name(athlete_id: int) -> str:
    conn = get_connection()
    try:
        row = conn.execute(
            "SELECT first_name, last_name FROM athletes WHERE id = ?",
            (int(athlete_id),),
        ).fetchone()
    finally:
        conn.close()

    if not row:
        return f"Athlete {athlete_id}"
    return f"{row[0] or ''} {row[1] or ''}".strip()


def _timed_training_build(athlete_id: int, today: dt.date):
    started = time.perf_counter()
    result = build_training_coach_detail(
        int(athlete_id),
        today=today,
    )
    return result, time.perf_counter() - started


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--athlete", type=int, required=True)
    parser.add_argument("--date", type=str, default=None)
    args = parser.parse_args()

    initialise_database()

    athlete_id = int(args.athlete)
    today = (
        dt.date.fromisoformat(args.date)
        if args.date
        else dt.date.today()
    )

    columns, original_rows = _backup_rows(athlete_id)
    original_count = len(original_rows)
    backup_path = _write_disk_backup(
        athlete_id,
        columns,
        original_rows,
    )

    print("Performance Passport v0.65.4 controlled cold-cache benchmark")
    print(f"Athlete: {_athlete_name(athlete_id)} ({athlete_id})")
    print(f"Date: {today.isoformat()}")
    print(f"Existing intelligence rows backed up: {original_count}")
    print(f"Safety backup: {backup_path}")
    print()
    print("Only derived athlete_intelligence rows are temporarily removed.")
    print("Athlete/source data is untouched.")
    print()

    cold_seconds = None
    warm_seconds = None

    try:
        removed = _delete_intelligence(athlete_id)
        remaining = _count_rows(athlete_id)
        print(f"Temporary cold-cache setup: removed {removed} rows; remaining {remaining}")

        if remaining != 0:
            raise RuntimeError(
                "Could not establish a clean athlete_intelligence cache"
            )

        print("\n=== TRUE COLD BUILD ===")
        cold_result, cold_seconds = _timed_training_build(
            athlete_id,
            today,
        )
        generated_after_cold = _count_rows(athlete_id)
        print(f"  Training Coach cold: {cold_seconds:.2f}s")
        print(f"  Intelligence rows generated: {generated_after_cold}")
        print(f"  Result returned: {cold_result is not None}")

        print("\n=== IMMEDIATE WARM BUILD ===")
        warm_result, warm_seconds = _timed_training_build(
            athlete_id,
            today,
        )
        print(f"  Training Coach warm: {warm_seconds:.2f}s")
        print(f"  Result returned: {warm_result is not None}")

        if warm_seconds > 0:
            print(
                f"\nCold-to-warm ratio: "
                f"{cold_seconds / warm_seconds:.1f}x"
            )

    finally:
        print("\n=== RESTORING ORIGINAL INTELLIGENCE ===")
        _restore_rows(
            athlete_id,
            columns,
            original_rows,
        )
        restored_count = _count_rows(athlete_id)
        print(
            f"  Restored rows: {restored_count} "
            f"(expected {original_count})"
        )
        if restored_count != original_count:
            print(
                "  WARNING: restored row count differs from the original. "
                f"Keep the safety backup at {backup_path}"
            )
        else:
            print("  Restore check: PASS")

    print("\n=== RESULT ===")
    if cold_seconds is not None:
        print(f"  True cold Training Coach: {cold_seconds:.2f}s")
    if warm_seconds is not None:
        print(f"  Warm Training Coach:      {warm_seconds:.2f}s")
    print(
        "\nUse the true cold number — not the earlier component-profile time — "
        "as the baseline for the next first-build optimisation."
    )


if __name__ == "__main__":
    main()
